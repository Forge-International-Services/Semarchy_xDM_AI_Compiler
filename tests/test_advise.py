def test_a_zero_merge_threshold_is_caught(s3):
    """docs/Design/matching/automate-merge-and-confirmation.md: the threshold is the
    score "above which the match group is automatically merged". Zero means merge at
    any score, so nothing is ever suggested and the steward queue stays empty because
    nothing is sent to it.

    Worth a rule because it is the DEFAULT state of a new matcher — reached by not
    deciding, and indistinguishable from a deliberate merge-everything policy. Observed
    on a live model built in the UI: 6 of the 8 thresholds sat at 0."""
    from agent.ir.advise import advise
    assert [g for g in advise(s3) if g.rule == "CA-015"] == []
    m = s3.certify.matchers[0]
    m.thresholds = {**m.resolved_thresholds(), "mergeThresholdMergingUnconfirmed": 0}
    hit = [g for g in advise(s3) if g.rule == "CA-015"]
    assert hit and "merges at ANY score" in hit[0].question


