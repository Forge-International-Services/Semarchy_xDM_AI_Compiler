def test_a_bin_is_never_coarser_than_the_equality_it_serves(s4):
    """LESSONS §46. Binning is the cost control: it decides which pairs are compared at
    all. P_NAME_STATE_ZIP binned on Address.StateCode alone — ~50 buckets — so every
    record in a US state was a candidate pair for every other. An over-matched group
    does not render slowly, it returns 504 on the duplicate manager's data call.

    The invariant: every binning key must appear in the rule's own condition, and a rule
    testing more than one equality must not bin on only the least selective one.
    """
    rule = next(r for x in s4.certify.matchers for r in x.rules
                if r.name == "P_NAME_STATE_ZIP")
    assert "NormalizedName" in rule.binning, \
        "the selective attribute must be in the bin, not just in the condition"
    for key in rule.binning:
        assert key in rule.condition, f"{key} bins on something the rule never tests"


